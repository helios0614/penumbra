import * as React from "react";
import { afterEach, expect, it, vi } from "vitest";
import { ChatExecutionReviewAction } from "./ChatExecutionReviewAction";
import { Button } from "@/components/ui/button";
import { Popover, PopoverContent } from "@/components/ui/popover";
import { find, hookSession } from "./test-utils/hook-session";
vi.mock("react", async original => {
  const actual = await original<typeof React>();
  return { ...actual, ...Object.fromEntries(["useState", "useRef", "useCallback", "useId", "useEffect", "useLayoutEffect"].map(key => [key, vi.fn(actual[key as keyof typeof actual] as never)])) };
});
afterEach(() => vi.restoreAllMocks());
it("separates explicit release from reading and explains that the previous request may continue", () => {
  const release = vi.fn();
  let ready = false;
  const hooks = hookSession(() => ChatExecutionReviewAction({ ready, onRelease: release }));
  expect(hooks.render()).toBeNull();
  ready = true;
  const tree = hooks.render();
  expect(release).not.toHaveBeenCalled();
  expect(JSON.stringify(find(tree, PopoverContent).props.children)).toContain("上一次请求可能仍在运行");
  expect(JSON.stringify(find(tree, PopoverContent).props.children)).toContain("不会取消后台任务，也不会自动重新发送");
  expect(JSON.stringify(find(tree, PopoverContent).props.children)).toContain("回复仍可能出现在聊天记录中");
  find(tree, Popover).props.onOpenChange?.(true, {} as never);
  const button = find(hooks.render(), Button, p => p.children === "保留临时回复，返回编辑");
  button.props.onClick?.({} as never);
  expect(release).toHaveBeenCalledOnce();
  expect(find(hooks.render(), Popover).props.open).toBe(false);
  ready = false;
  expect(hooks.render()).toBeNull();
});
